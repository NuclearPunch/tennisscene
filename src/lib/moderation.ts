/**
 * 올리기 전 거르기 — 애플 1.2 "부적절한 글을 걸러내는 방법".
 *
 * **첫 번째 그물일 뿐이다.** 여기서 못 거른 건 신고(익명 2건·실명 3건이면 자동 블라인드)와
 * 관리자 큐가 받는다. 그래서 목록은 좁게 둔다 — 애매한 말까지 막으면 멀쩡한 글이 막혀서
 * 사람들이 쓰기를 포기한다.
 *
 * 걸리면 안 되는 말: "미친 샷"(칭찬), "시발점", "존나"(험하지만 욕을 향하지 않는 강조).
 * 걸려야 하는 말: 욕설, 사람을 향한 비하, 혐오 표현.
 *
 * 글자 사이에 점·숫자·기호를 끼워 피하는 것("씨1발", "병.신")은 잡는다.
 * 띄어쓰기로 피하는 것("시 발")은 안 잡는다 — 띄어쓰기까지 지우면 "다시 발리" 가 걸린다.
 */

const PATTERNS: RegExp[] = [
  // 욕설
  /씨발|씨바|씨팔|시팔|쌍년|썅|좆|ㅆㅂ|ㅅㅂ/,
  /시발(?!점|역)/,
  /병신|븅신|ㅂㅅ/,
  /개새끼|개새기|개색기|개색끼|개쌔끼/,
  /니애미|느금마|느개비|니미럴/,
  /미친년|미친놈|미친새끼/,
  // 성적인 말
  /섹스|창녀|강간/,
  // 집단을 향한 혐오 표현
  /틀딱|한남충|김치녀|맘충|급식충|짱깨|쪽바리/,
];

/** 한글 사이에 끼운 점·숫자·기호를 뺀다. 띄어쓰기는 남긴다. */
function squeeze(text: string): string {
  return text.replace(/(?<=[가-힣ㄱ-ㅎ])[.\-_*~!|/\\0-9]+(?=[가-힣ㄱ-ㅎ])/g, "");
}

/** 걸린 표현이 있으면 true. 어떤 말인지는 돌려주지 않는다 — 화면에 그대로 띄울 말이 아니다. */
export function hasBlockedWords(text: string): boolean {
  const variants = [text, squeeze(text)];
  return variants.some((t) => PATTERNS.some((re) => re.test(t)));
}

export const BLOCKED_MESSAGE = "욕설이나 비하·혐오 표현이 들어간 글은 올릴 수 없습니다";
